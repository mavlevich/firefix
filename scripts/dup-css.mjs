// Writes the userChrome.css rules that light up one group of duplicate tabs.
// There is one selector per group code from extensions/firefix/lib/duplicates.js,
// so run this again whenever the codes change:
//
//   node scripts/dup-css.mjs
//
// A test checks that userChrome.css matches what this script would write.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { GROUP_CODES, MARKER } from "../extensions/firefix/lib/duplicates.js";

export const START = "/* Duplicate groups: start. Generated by scripts/dup-css.mjs, do not edit by hand. */";
export const END = "/* Duplicate groups: end. */";

const escape = (text) => [...text].map((char) => `\\${char.codePointAt(0).toString(16)}`).join("");

// One selector per group code: when the selected or the hovered tab carries that code,
// it matches every tab with the same code, the tab itself included.
function litSelectors(part) {
  return GROUP_CODES.map((code) => {
    const label = `[label^="${escape(MARKER + code)}"]`;
    return (
      `#tabbrowser-tabs:has(.tabbrowser-tab:is([visuallyselected], :hover)${label})` +
      ` .tabbrowser-tab${label} > .tab-stack > ${part}`
    ).trim();
  }).join(",\n");
}

// The lit group gets an amber edge, and its LEDs glow brighter. Other groups stay as they are.
export function groupBlock() {
  return [
    START,
    `${litSelectors(".tab-background")} {`,
    "  outline: 1px solid var(--firefix-dup) !important;",
    "  outline-offset: -1px !important;",
    "  box-shadow: 0 0 8px var(--firefix-dup-glow) !important;",
    "}",
    "",
    `${litSelectors(".tab-background::after")} {`,
    "  box-shadow: var(--firefix-dup-led-glow-lit);",
    "}",
    END,
  ].join("\n");
}

export function updateCss(css) {
  const start = css.indexOf(START);
  const end = css.indexOf(END);
  if (start === -1 || end === -1) throw new Error("Duplicate group markers not found in userChrome.css");
  return css.slice(0, start) + groupBlock() + css.slice(end + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = fileURLToPath(new URL("../profile/chrome/userChrome.css", import.meta.url));
  writeFileSync(file, updateCss(readFileSync(file, "utf8")));
}
